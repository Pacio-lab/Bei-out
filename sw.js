function rotateAds() {
    const adTitleEl = document.getElementById('ad-title');
    const adTextEl = document.getElementById('ad-text');
    const adImgEl = document.getElementById('ad-img');
    const adLinkEl = document.getElementById('ad-link');
    const card = document.getElementById('dynamic-ad-card');
    
    if(!card) return;
    card.style.opacity = '0.3';

    setTimeout(() => {
        const currentAd = adsPool[currentAdIndex];
        adTitleEl.textContent = currentAd.title;
        adTextEl.textContent = (currentLang === 'en') ? currentAd.textEn : currentAd.textIt;
        adImgEl.src = currentAd.img;
        adLinkEl.href = currentAd.link;
        card.style.opacity = '1';
        card.style.display = 'block';

        currentAdIndex = (currentAdIndex + 1) % adsPool.length;
    }, 300);
}

function updateSponsorText() {
    const adTextEl = document.getElementById('ad-text');
    if(adTextEl) {
        const currentAd = adsPool[(currentAdIndex - 1 + adsPool.length) % adsPool.length];
        adTextEl.textContent = (currentLang === 'en') ? currentAd.textEn : currentAd.textIt;
    }
}

function filterEvents(value, btn, type) {
    const parentContainer = btn.parentElement;
    parentContainer.querySelectorAll('.filter-btn').forEach(b => b.classList.remove('active'));
    btn.classList.add('active');

    if (type === 'zone') currentZone = value;
    if (type === 'music') currentMusic = value;

    const cards = document.querySelectorAll('.event-card');
    cards.forEach(card => {
        const cardZone = card.dataset.category;
        const cardMusic = card.dataset.music;

        const matchZone = (currentZone === 'all' || cardZone === currentZone);
        const matchMusic = (currentMusic === 'all' || cardMusic === currentMusic);

        if (matchZone && matchMusic) {
            card.style.display = 'block';
        } else {
            card.style.display = 'none';
        }
    });
}

function toggleDarkMode() {
    document.body.classList.toggle('dark-mode');
    updateTexts();
}

function shareStory(clubName, zone) {
    const shareText = `Stasera si va da ${clubName} (${zone})! 🔥 Scopri gli eventi su BRIXIAOUT 🚀`;
    if (navigator.clipboard) {
        navigator.clipboard.writeText(shareText).then(() => {
            alert('📋 Testo copiato! Incollalo ora nelle tue Stories di Instagram o TikTok.');
        });
    } else {
        alert(shareText);
    }
}

window.onload = function() {
    rotateAds();
    setInterval(rotateAds, 5000);
    
    if ('serviceWorker' in navigator) {
        navigator.serviceWorker.register('./sw.js')
            .then(reg => console.log('Service Worker PWA attivo!', reg))
            .catch(err => console.log('Errore Service Worker:', err));
    }
};
